ORDERING_COLUMN = "jet_energy"
SCALAR_TOPOLOGY_COLUMNS = ("event_invariant_mass", "n_jets_original")
PAIR_TOPOLOGY_COLUMNS = ("jet_energy", "jet_pt", "jet_p", "jet_theta")
NUMBER_OF_JETS = 2


@dataclass
class EventData:
    jet_inputs: np.ndarray       # [event, jet, per-jet feature]
    topology: np.ndarray         # [event, topology feature]
    weights: np.ndarray          # expected-yield/event weights
    processes: np.ndarray        # process name for composition/templates
    used_physical_weights: bool
    missing: dict[str, int]
    infinities: dict[str, int]


@dataclass(frozen=True)
class SampleNormalization:
    name: str
    class_name: str
    path_glob: str
    cross_section_pb: float
    generated_events: dict[str, float]
    filter_efficiency: float = 1.0
    k_factor: float = 1.0
    branching_fraction: float = 1.0

    def weight(self, split: str, luminosity_ab_inv: float) -> float:
        if split not in self.generated_events:
            raise ValueError(
                f"Sample {self.name!r} has no generated_events entry for split {split!r}"
            )
        denominator = float(self.generated_events[split])
        if denominator <= 0:
            raise ValueError(
                f"Sample {self.name!r}: generated_events[{split!r}] must be positive"
            )
        # 1 pb * 1 ab^-1 = 10^6 expected events.
        return (self.cross_section_pb * luminosity_ab_inv * 1.0e6
                * self.filter_efficiency * self.k_factor
                * self.branching_fraction / denominator)


