#!/usr/bin/env python3
"""Train a leakage-safe event BDT from two jet scores plus event topology.

The test split is never opened.  Training-event jet scores are generated by
event-level cross-fitting by default, while validation scores are generated by
the supplied full per-jet model.  This prevents the stacked event classifier
from learning from in-sample jet-tagger predictions.

Default event inputs (12)
-------------------------
* leading_jet_score, subleading_jet_score;
* event_invariant_mass, n_jets_original;
* leading/subleading jet_energy, jet_pt, jet_p and jet_theta.

The two jets and every jet-level observable are ordered by decreasing energy.
Physical weights can be supplied either in an ``event_weight`` Parquet column
or through a per-process JSON normalization manifest.  The manifest route uses

    weight = sigma_pb * luminosity_ab^-1 * 1e6
             * filter_efficiency * k_factor * branching_fraction / N_generated

where ``N_generated`` is specified separately for train and validation.  If no
physical normalization is available, unit weights are used and significance is
explicitly labelled as an unnormalised proxy.
"""

